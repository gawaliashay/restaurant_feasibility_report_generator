# src/workflow/report/report_compiler.py

"""
Stack section reports into one markdown document. No LLM.
"""

from datetime import datetime
from typing import Any

from src.configuration.config_loader import config_loader


class ReportCompiler:
    """Compile the final report from section_reports."""

    def compile(self, state: dict[str, Any]) -> str:
        reports = state.get("section_reports", {})
        research = state.get("research_results", {})
        total = self._evidence_count(research)
        parts = [
            self._header(state),
            self._summary(state, total, reports),
            self._body(reports),
            self._conclusion(state, total, reports),
        ]
        return "\n\n".join(part for part in parts if part)

    def _evidence_count(self, research: dict) -> int:
        total = 0
        for name, config in config_loader.get("research.sections", {}).items():
            if config.get("enabled", True):
                total += len(research.get(name, {}).get("evidence", []))
        return total

    def _title(self, config: dict, name: str) -> str:
        return config.get("title", name).replace(" Report", "")

    def _header(self, state: dict) -> str:
        return "\n".join([
            "# RESTAURANT FEASIBILITY REPORT",
            "",
            f"**Concept:** {state.get('restaurant_concept', '')}",
            f"**Location:** {state.get('local_area', '')}, {state.get('city', '')}",
            f"**Investment:** {state.get('investment', '')}",
            f"**Date:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
            "",
            "---",
        ])

    def _summary(self, state: dict, total: int, reports: dict) -> str:
        lines = [
            "## Executive Summary",
            "",
            f"**{state.get('restaurant_concept', '')}** in "
            f"**{state.get('local_area', '')}, {state.get('city', '')}** — {total} evidence items.",
            "",
        ]
        for name, config in config_loader.get("report.sections", {}).items():
            if name == "strategic_recommendations":
                continue
            if not config.get("enabled", True):
                continue
            result = reports.get(name, {})
            if result.get("status") != "success":
                continue
            blurb = self._first_paragraph(result.get("report", ""))
            if blurb:
                lines.append(f"- **{self._title(config, name)}:** {blurb}")
        lines.extend(["", "---"])
        return "\n".join(lines)

    def _body(self, reports: dict) -> str:
        parts = []
        for name, config in config_loader.get("report.sections", {}).items():
            if not config.get("enabled", True):
                continue
            result = reports.get(name, {})
            if result.get("status") != "success":
                continue
            text = (result.get("report") or "").strip()
            if not text:
                continue
            # Section title is ##; LLM ## headings become ###.
            body = "\n".join(
                "#" + line if line.startswith("## ") else line
                for line in text.split("\n")
            )
            parts.append(f"## {self._title(config, name)}\n\n{body}\n\n---")
        return "\n".join(parts)

    def _first_paragraph(self, text: str, max_chars: int = 200) -> str:
        for line in text.split("\n"):
            clean = line.strip()
            if not clean or len(clean) <= 10:
                continue
            if clean[0] in "#|-*":
                continue
            if clean[0].isdigit() and ". " in clean[:4]:
                continue
            if clean.lower().startswith("sources:"):
                continue
            idx = clean.find(". ")
            if idx > 20:
                clean = clean[: idx + 1]
            if len(clean) > max_chars:
                clean = clean[:max_chars].rsplit(" ", 1)[0] + "..."
            return clean
        return ""

    def _conclusion(self, state: dict, total: int, reports: dict) -> str:
        strategy = reports.get("strategic_recommendations", {}).get("report", "")
        lines = [
            "## Conclusion",
            "",
            f"**{state.get('restaurant_concept', '')}** in "
            f"**{state.get('local_area', '')}, {state.get('city', '')}**. "
            f"Investment **{state.get('investment', '')}**. "
            f"Based on {total} evidence items.",
            "",
        ]
        verdict = self._verdict(strategy)
        if verdict:
            lines.extend([f"**Verdict:** {verdict}", ""])
        steps = self._first_numbered(strategy, limit=5)
        if steps:
            lines.append("### Next steps")
            lines.extend(f"- {step}" for step in steps)
            lines.append("")
        lines.extend(["---", "", "*Report generated by AI*"])
        return "\n".join(lines)

    def _verdict(self, text: str) -> str:
        for line in text.split("\n"):
            clean = line.strip()
            upper = clean.upper()
            if upper.startswith("GO,") or upper.startswith("GO ") or upper in ("GO", "NO GO"):
                return clean[:400]
            if upper.startswith("CONDITIONAL GO"):
                return clean[:400]
        return ""

    def _first_numbered(self, text: str, limit: int = 5) -> list[str]:
        items = []
        for line in text.split("\n"):
            clean = line.strip()
            if clean[:1].isdigit() and ". " in clean[:4]:
                items.append(clean.split(". ", 1)[1])
                if len(items) >= limit:
                    break
        return items
